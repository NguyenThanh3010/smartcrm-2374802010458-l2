-- 002: User accounts and ticket ownership

-- 1. User accounts
CREATE TABLE app_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'STAFF',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_app_user_role
        CHECK (role IN ('ADMIN', 'STAFF'))
);

-- 2. Add ticket owner
-- Temporarily nullable to allow existing tickets to be assigned
-- to the initial administrator during application initialization.
ALTER TABLE ticket
    ADD COLUMN created_by BIGINT;

ALTER TABLE ticket
    ADD CONSTRAINT fk_ticket_created_by
    FOREIGN KEY (created_by)
    REFERENCES app_user(user_id);

-- 3. Support owner-based ticket queries
CREATE INDEX idx_ticket_created_by
    ON ticket(created_by);